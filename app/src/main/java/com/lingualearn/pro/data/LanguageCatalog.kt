    val optionalCourses: List<LanguageCourse> = extras.map { extra ->
        LanguageCourse(
            id = extra.id,
            name = extra.name,
            flag = extra.flag,
            progress = 0,
            level = "Beginner",
            accent = extra.accent,
            recentLessons = listOf("Basic Greetings", "Numbers 1–10", "Everyday Phrases"),
            localeTag = extra.localeTag,
            optional = true,
            nativeLabel = extra.nativeLabel,
        )
    }

    private fun extra(courseId: String): ExtraLanguage? = extras.firstOrNull { it.id == courseId }

    fun activityPack(courseId: String): SampleContent.ActivityPack? {
        val extra = extra(courseId) ?: return null
        val vocab = listOf(
            VocabWord(extra.apple, "apple", "\uD83C\uDF4E"),
            VocabWord(extra.car, "car", "\uD83D\uDE97"),
            VocabWord(extra.house, "house", "\uD83C\uDFE0"),
            VocabWord(extra.dog, "dog", "\uD83D\uDC15"),
            VocabWord(extra.water, "water", "\uD83D\uDCA7"),
            VocabWord(extra.book, "book", "\uD83D\uDCDA"),
        )
        return SampleContent.ActivityPack(
            vocabulary = vocab,
            nativeLabel = extra.nativeLabel,
            listeningTitle = "${extra.name} Daily Phrases",
            listeningDescription = "Listen to beginner-friendly ${extra.name} clips",
            listeningPhrases = listOf(
                GrammarExample(extra.howAreYou, extra.howAreYouEn),
                GrammarExample(extra.station, extra.stationEn),
                GrammarExample(extra.cafe, extra.cafeEn),
                GrammarExample(extra.thanks, "Thank you."),
                GrammarExample(extra.hello, "Hello."),
            ),
            writingPrompt = "Describe your ideal vacation in ${extra.name} (40 words minimum)",
            writingPlaceholder = "Write here…",
            writingSuccess = "Great work! Your tutor will review this entry.",
            tutorGreeting = "${extra.hello}! I'm your AI ${extra.name} tutor. How can I help you today?",
            tutorPlaceholder = "Ask me anything about ${extra.name}...",
            tutorReplies = listOf(
                "Nice try! Let’s practice that phrase again out loud.",
                "Tip: learn useful chunks, not only single words.",
                "Want a quick quiz on greetings next?",
            ),
            conversationNote = "Practice these scenarios in ${extra.name}",
        )
    }

    fun dailyGrammarLesson(courseId: String): DailyGrammarLesson? {
        val extra = extra(courseId) ?: return null
        return DailyGrammarLesson(
            number = 1,
            title = "Greetings and polite phrases",
            subtitle = "Start real conversations in ${extra.name}",
            level = "Beginner",
            concept = "Beginner ${extra.name} starts with greetings, thanks, and simple requests you can use the same day.",
            rule = "Memorize high-frequency phrases first, then swap in new nouns. Politeness words like “${extra.please}” and “${extra.thanks}” belong in almost every exchange.",
            examples = listOf(
                GrammarExample(extra.hello, "Hello."),
                GrammarExample(extra.howAreYou, extra.howAreYouEn),
                GrammarExample("${extra.thanks}.", "Thank you."),
            ),
            questions = listOf(
                ExerciseQuestion(
                    "How do you say hello in ${extra.name}?",
                    listOf(extra.hello, extra.thanks, extra.water),
                    0,
                    "${extra.hello} is the everyday greeting.",
                ),
                ExerciseQuestion(
                    "Which phrase means “thank you”?",
                    listOf(extra.friend, extra.thanks, extra.one),
                    1,
                    "${extra.thanks} means thank you.",
                ),
                ExerciseQuestion(
                    "Choose the best match for: ${extra.howAreYou}",
                    listOf(extra.howAreYouEn, "Where is the station?", "I would like coffee."),
                    0,
                    "This is the common “how are you?” phrase.",
                ),
            ),
        )
    }

    fun dictionaryWords(courseId: String): List<VocabWord>? {
        val extra = extra(courseId) ?: return null
        return listOf(
            VocabWord(extra.hello, "hello"),
            VocabWord(extra.thanks, "thank you"),
            VocabWord(extra.one, "one"),
            VocabWord(extra.two, "two"),
            VocabWord(extra.friend, "friend"),
            VocabWord(extra.water, "water"),
            VocabWord(extra.please, "please"),
        )
    }

    fun pronunciationPhrases(courseId: String): List<GrammarExample>? {
        val extra = extra(courseId) ?: return null
        return listOf(
            GrammarExample(extra.howAreYou, extra.howAreYouEn),
            GrammarExample(extra.cafe, extra.cafeEn),
            GrammarExample(extra.station, extra.stationEn),
        )
    }

    fun localeTag(courseId: String): String? = extra(courseId)?.localeTag
